export const DAY = 86400000;

export function nowIso() {
  return new Date().toISOString();
}

export function daysSince(iso) {
  if (!iso) return null;
  const t = Date.parse(iso);
  if (Number.isNaN(t)) return null;
  return Math.floor((Date.now() - t) / DAY);
}

export function humanSize(kib) {
  const n = Number(kib) || 0;
  if (n < 1024) return `${n} KB`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} MB`;
  return `${(n / 1024 / 1024).toFixed(2)} GB`;
}

export function clamp(n, lo, hi) {
  return Math.max(lo, Math.min(hi, n));
}

export function lines(s) {
  return String(s || '').split('\n').filter((l) => l.length > 0);
}

/** 匹配 AI 参与痕迹（启发式，UI 上必须标注“估算”） */
const AI_COAUTHOR = /co-authored-by:[^\n]*(claude|anthropic|copilot|openai|gpt|cursor|codeium|windsurf|gemini|devin|aider|cline|continue|zed)/i;
const AI_MARK = /(generated with|generated by|ai-generated|assisted by|\[ai\]|\u{1F916})/iu;
const AI_AUTHOR = /(copilot|cursor|\bai\b|bot)$/i;

export function looksLikeAI({ subject = '', body = '', author = '' }) {
  const text = `${subject}\n${body}`;
  if (AI_COAUTHOR.test(text)) return true;
  if (AI_MARK.test(text)) return true;
  if (AI_AUTHOR.test(author.trim())) return true;
  return false;
}

export function uniq(arr) {
  return Array.from(new Set(arr));
}
