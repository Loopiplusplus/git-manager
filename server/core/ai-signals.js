/**
 * AI 协作痕迹检测（启发式 · 可解释 · 纯本地）
 *
 * ── 为什么不用一个简单的正则 ──
 * 最早的实现只扫提交信息里的关键词（「Generated with …」「Co-Authored-By: Claude」），
 * 结果自己在整个仓库里写了 7 个提交却报 0% —— 因为绝大多数 AI 写作的提交
 * 并不会在信息里留下署名。这个指标因此变成了摆设。
 *
 * ── 现在的做法 ──
 * 用多路信号累加打分，并且把**每一条依据摊开给用户看**，而不是甩一个百分比：
 *   1. 显式证据（署名 / 生成标记 / 机器人 / AI 作者名）—— 单条即可定性；
 *   2. 形态证据（结构化长正文、规范前缀、装饰字符、超长标题）—— 需要累积；
 *   3. 过程证据（提交间隔极短、单次改动量远超常态）—— 需要累积。
 *
 * ── 诚实边界（必须在 UI 上写明，不能糊弄）──
 * · 这是「痕迹推断」，不是事实判定。**没检出痕迹 ≠ 没有 AI 参与**：
 *   本仓库就有 2 个提交正文为空，任何只看信息的规则都拿它们没办法。
 * · 仅靠形态证据最多只能判到「疑似」，永远不给「高置信」——
 *   因为一个严谨的人类开发者同样会写结构化长正文。
 * · 只有显式证据才给「高置信」。
 * · 启发式可能误判，所以证据必须可见、可被用户推翻。
 *
 * ── 隐私 ──
 * 只读 git 元数据（提交信息、作者、时间、改动行数）与**文件路径名**。
 * 不读取任何文件内容，不联网，不上传任何数据。全程在本机完成。
 */

/* ============================ 强证据 ============================ */

const RE_COAUTHOR =
  /co-authored-by:[^\n]*(claude|anthropic|copilot|openai|gpt|cursor|codeium|windsurf|gemini|devin|aider|cline|continue|zed|codex|tabnine|cody|qwen|deepseek|kimi|通义|文心|豆包)/i;
const RE_GENERATED =
  /(generated with|ai-generated|assisted by|\u005Bai\u005D|\u{1F916}|generated by (claude|copilot|cursor|openai|gpt|aider|codex|an ai))/iu;
const RE_BOT_AUTHOR =
  /(\[bot\]$|(^|[-_ ])bot$|^bot[-_]|dependabot|renovate|github-actions|actions-user|greenkeeper|snyk-bot|imgbot|mergify)/i;
const RE_AI_AUTHOR = /^(claude|copilot|cursor|codex|aider|devin|windsurf|gemini|chatgpt|openai|anthropic|zed)\b/i;

/** 只在仓库里出现文件，就说明有 AI 代理在这个项目上工作过 */
export const AGENT_FILE_PATTERNS = [
  [/^CLAUDE\.md$/i, 'Claude Code'],
  [/^AGENTS\.md$/i, '通用 AGENTS 约定'],
  [/^GEMINI\.md$/i, 'Gemini CLI'],
  [/^\.cursorrules$/i, 'Cursor'],
  [/^\.windsurfrules$/i, 'Windsurf'],
  [/^\.clinerules/i, 'Cline'],
  [/^\.aider/i, 'Aider'],
  [/^\.cursor\//i, 'Cursor'],
  [/^\.claude\//i, 'Claude Code'],
  [/^\.codex\//i, 'Codex'],
  [/^\.gemini\//i, 'Gemini CLI'],
  [/^\.continue\//i, 'Continue'],
  [/^\.roo\//i, 'Roo Code'],
  [/^\.trae\//i, 'Trae'],
  [/^\.github\/copilot/i, 'GitHub Copilot'],
  [/^\.workbuddy\//i, 'WorkBuddy'],
  [/^\.codebuddy\//i, 'CodeBuddy'],
];

/* ============================ 形态证据 ============================ */

const RE_CONVENTIONAL = /^(feat|fix|chore|docs|refactor|test|perf|style|build|ci|revert|release)(\([^)]*\))?!?:/;
const RE_DECOR = /[★☆✅❌⚠❗✔①-⑳]|\p{Extended_Pictographic}/u;

/* ============================ 权重与阈值 ============================ */

/** 单条即定性（显式证据） */
const EXPLICIT_WEIGHT = 90;

/** 仅靠启发式时，level 的上限 —— 形态证据再充分也不给「高置信」 */
const HEURISTIC_CAP = 'likely';

const THRESHOLD = { weak: 25, likely: 60 };

export const LEVEL_LABEL = {
  high: '高置信',
  likely: '疑似',
  weak: '弱痕迹',
  none: '未发现',
};

export const DISCLAIMER =
  '这是基于本地 git 元数据的痕迹推断，不是事实判定。没检出痕迹不代表没有 AI 参与——例如正文为空的提交就无迹可寻。' +
  '仅凭提交形态最多判为「疑似」，因为严谨的人类开发者也会写出同样规范的信息。';

/* ============================ 信号定义 ============================ */

const def = (id, label, weight, detail, test) => ({ id, label, weight, detail, test });

const SIGNALS = [
  def('coauthor', '提交信息含 AI 协作署名', 100, 'Co-Authored-By 指向 AI 工具',
    (c) => (RE_COAUTHOR.test(c.text) ? '匹配到 co-authored-by 署名' : null)),
  def('generated-mark', '提交信息含生成标记', 100, '如 “Generated with …” / 🤖',
    (c) => (RE_GENERATED.test(c.text) ? '匹配到生成标记' : null)),
  def('bot-author', '作者或提交者是机器人', 100, '如 [bot] / dependabot',
    (c) => {
      if (RE_BOT_AUTHOR.test(c.author)) return `作者 ${c.author}`;
      if (c.committer && RE_BOT_AUTHOR.test(c.committer)) return `提交者 ${c.committer}`;
      return null;
    }),
  def('ai-author-name', '作者名就是 AI 工具', 90, '如 claude / copilot / cursor',
    (c) => (RE_AI_AUTHOR.test(c.author) ? `作者 ${c.author}` : null)),

  def('structured-body', '正文结构化成文', 25, '分段 + 编号列表或小标题',
    (c) => (isStructured(c.body) ? '正文含列表或多个小标题' : null)),
  def('long-body', '正文明显偏长', 20, '正文 ≥300 字，或显著高于仓库中位数',
    (c) => {
      const len = c.bodyLength;
      if (len < 120) return null;
      if (len >= 300) return `正文 ${len} 字`;
      if (c.ctx.medianBody >= 80 && len >= c.ctx.medianBody * 3) return `正文 ${len} 字（仓库中位数 ${c.ctx.medianBody} 字）`;
      return null;
    }),
  def('decorated', '使用装饰字符或 emoji', 15, '如 ★ ✅ ⚠ 🤖 ①',
    (c) => {
      const m = `${c.subject}\n${c.body}`.match(RE_DECOR);
      return m ? `出现 ${JSON.stringify(m[0])}` : null;
    }),
  def('conventional', '使用 Conventional Commits 前缀', 8, '如 feat(scope): / fix:',
    (c) => (RE_CONVENTIONAL.test(c.subject) ? c.subject.match(RE_CONVENTIONAL)[0] : null)),
  def('long-subject', '标题偏长', 8, '标题 ≥40 字（惯例是 ≤50 字符）',
    (c) => (c.subjectLength >= 40 ? `${c.subjectLength} 字` : null)),

  def('burst', '与相邻提交间隔极短', 12, '同一轮里 10 分钟内连提',
    (c) => {
      const gap = c.ctx.minNeighborGapSec;
      if (gap === null || gap === undefined) return null;
      return gap <= 600 ? `相邻提交间隔 ${fmtGap(gap)}` : null;
    }),
  def('huge-diff', '单次改动量远超仓库常态', 10, '新增行数 ≥ 仓库中位数 3 倍且 ≥300',
    (c) => {
      if (c.added === null || c.added === undefined) return null;
      const med = c.ctx.medianAdded;
      if (!med || med <= 0) return null;
      const bar = Math.max(300, med * 3);
      return c.added >= bar ? `新增 ${c.added} 行（中位数 ${med} 行）` : null;
    }),
];

/* ============================ 工具函数 ============================ */

function isStructured(body) {
  const ls = String(body || '')
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean);
  if (ls.length < 4) return false;
  const bullets = ls.filter((l) => /^([-*•]|\d+[.)、]|[①-⑳])\s*\S/.test(l)).length;
  const heads = ls.filter((l) => /[：:]$/.test(l) && l.length <= 24).length;
  return bullets >= 3 || heads >= 2;
}

function fmtGap(sec) {
  if (sec < 60) return `${sec} 秒`;
  return `${Math.round(sec / 60)} 分钟`;
}

function median(nums) {
  const a = nums.filter((n) => Number.isFinite(n)).sort((x, y) => x - y);
  if (!a.length) return 0;
  const m = Math.floor(a.length / 2);
  return a.length % 2 ? a[m] : Math.round((a[m - 1] + a[m]) / 2);
}

/* ============================ git log 解析 ============================ */

export const US = '\x1f';
export const RS = '\x1e';

/**
 * 一次 git log 同时拿到提交元数据与改动量。
 * 记录分隔符放在**行首**，这样每条记录后面的 shortstat 归属正确（放行尾会整体错位一格）。
 */
export const LOG_FORMAT = `%x1e%H${US}%h${US}%an${US}%cn${US}%at${US}%s${US}%b`;

const RE_SHORTSTAT = /^(\d+) files? changed(?:, (\d+) insertions?\(\+\))?(?:, (\d+) deletions?\(-\))?$/;

export function parseLogWithShortstat(raw) {
  return String(raw || '')
    .split(RS)
    .filter((s) => s.trim())
    .map((rec) => {
      const ls = rec.split('\n');
      while (ls.length && !ls[0].trim()) ls.shift();
      while (ls.length && !ls[ls.length - 1].trim()) ls.pop();

      // shortstat 一定是最后一条非空行，且形如 "3 files changed, 120 insertions(+), 4 deletions(-)"。
      // 只认行首行尾，避免提交正文里恰好提到这句话时被误当成改动量。
      let added = null;
      let deleted = null;
      if (ls.length) {
        const m = ls[ls.length - 1].trim().match(RE_SHORTSTAT);
        if (m) {
          added = Number(m[2] || 0);
          deleted = Number(m[3] || 0);
          ls.pop();
          while (ls.length && !ls[ls.length - 1].trim()) ls.pop();
        }
      }

      const p = ls.join('\n').split(US);
      while (p.length < 7) p.push('');
      return {
        hash: p[0],
        short: p[1],
        author: p[2],
        committer: p[3],
        at: p[4],
        subject: p[5],
        body: p.slice(6).join(US).trim(),
        // null 表示"未知"（没有 shortstat），而不是"零改动"
        added,
        deleted,
      };
    });
}

/** 从被跟踪的文件路径里找出 AI 工具痕迹（只看文件名，不读内容） */
export function detectAgentFiles(filePaths) {
  const hits = new Map();
  for (const p of filePaths) {
    for (const [re, tool] of AGENT_FILE_PATTERNS) {
      if (re.test(p)) {
        if (!hits.has(tool)) hits.set(tool, []);
        if (hits.get(tool).length < 3) hits.get(tool).push(p);
        break;
      }
    }
  }
  return Array.from(hits, ([tool, files]) => ({ tool, files }));
}

/** 由整批提交算出基线（中位数、相邻间隔），供各信号比较 */
export function buildContext(records) {
  const times = records.map((r) => Number(r.at) || 0).filter(Boolean).sort((a, b) => a - b);
  const gaps = [];
  for (let i = 1; i < times.length; i += 1) gaps.push(times[i] - times[i - 1]);

  return {
    count: records.length,
    medianAdded: median(records.map((r) => Number(r.added)).filter((n) => Number.isFinite(n))),
    medianBody: median(records.map((r) => String(r.body || '').trim().length)),
    times,
    gaps,
    // 样本太少时基线不可靠，相关信号一律不启用
    reliable: records.length >= 3,
  };
}

/** 单条提交 → { score, level, basis, signals[] } */
export function analyzeCommit(rec, ctx) {
  const body = String(rec.body || '').trim();
  const subject = String(rec.subject || '');
  const at = Number(rec.at) || 0;

  // 找最近的一次相邻间隔
  let minNeighborGapSec = null;
  if (ctx.reliable && at) {
    for (const t of ctx.times) {
      const g = Math.abs(t - at);
      if (g === 0) continue;
      if (minNeighborGapSec === null || g < minNeighborGapSec) minNeighborGapSec = g;
    }
  }

  const c = {
    subject,
    body,
    text: `${subject}\n${body}`,
    author: String(rec.author || ''),
    committer: String(rec.committer || ''),
    subjectLength: [...subject].length,
    bodyLength: body.length,
    added: Number.isFinite(Number(rec.added)) ? Number(rec.added) : null,
    ctx: ctx.reliable ? ctx : { ...ctx, medianAdded: 0, medianBody: 0 },
  };
  c.ctx.minNeighborGapSec = ctx.reliable ? minNeighborGapSec : null;

  const hits = [];
  for (const s of SIGNALS) {
    let detail = null;
    try {
      detail = s.test(c);
    } catch {
      detail = null; // 单个信号出错绝不影响整体
    }
    if (detail) hits.push({ id: s.id, label: s.label, weight: s.weight, detail });
  }

  const score = hits.reduce((n, h) => n + h.weight, 0);
  const explicit = hits.some((h) => h.weight >= EXPLICIT_WEIGHT);

  let level;
  if (explicit) level = 'high';
  else if (score >= THRESHOLD.likely) level = HEURISTIC_CAP;
  else if (score >= THRESHOLD.weak) level = 'weak';
  else level = 'none';

  return { score, level, basis: explicit ? 'explicit' : 'heuristic', signals: hits };
}

/** 汇总成给前端用的结构 */
export function summarize(analyzed, agentFiles) {
  const counts = { high: 0, likely: 0, weak: 0, none: 0 };
  for (const a of analyzed) counts[a.level] += 1;

  const sampled = analyzed.length;
  const flagged = counts.high + counts.likely;

  // 每条信号的命中次数，按命中数排序 —— 用户一眼能看出「是靠什么判的」
  const bySignal = new Map();
  for (const a of analyzed) {
    for (const h of a.signals) {
      const cur = bySignal.get(h.id) || { id: h.id, label: h.label, weight: h.weight, hits: 0, sample: h.detail };
      cur.hits += 1;
      bySignal.set(h.id, cur);
    }
  }

  const signals = [...bySignal.values()].sort((a, b) => b.hits - a.hits || b.weight - a.weight);

  let level = 'none';
  if (counts.high > 0) level = 'high';
  else if (counts.likely > 0) level = 'likely';
  else if (counts.weak > 0) level = 'weak';

  return {
    sampled,
    // 主指标：明确留下痕迹（疑似及以上）的提交占比
    ratio: sampled ? Number((flagged / sampled).toFixed(4)) : 0,
    flagged,
    counts,
    level,
    signals,
    hasExplicit: counts.high > 0,
    agentFiles,
    // 仓库里明明有 AI 工具痕迹，却仍有提交没留下任何痕迹
    // → 说明「未检出」只是因为提交信息里没线索，估算很可能偏低。必须如实提示。
    likelyUnderestimated: agentFiles.length > 0 && flagged < sampled,
    untraced: sampled - flagged,
    isEstimate: true,
    disclaimer: DISCLAIMER,
  };
}

export function emptySummary() {
  return {
    sampled: 0,
    ratio: 0,
    flagged: 0,
    counts: { high: 0, likely: 0, weak: 0, none: 0 },
    level: 'none',
    signals: [],
    hasExplicit: false,
    agentFiles: [],
    likelyUnderestimated: false,
    untraced: 0,
    isEstimate: true,
    disclaimer: DISCLAIMER,
  };
}
